CREATE TABLE cliente (
    id_cliente NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador VARCHAR2(50) UNIQUE NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    telefono VARCHAR2(20),
    correo VARCHAR2(100)
);

CREATE TABLE vehiculo (
    id_vehiculo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa VARCHAR2(20) UNIQUE NOT NULL,
    marca VARCHAR2(50) NOT NULL,
    modelo VARCHAR2(50) NOT NULL,
    anio NUMBER(4),
    id_cliente NUMBER NOT NULL,
    CONSTRAINT fk_vehiculo_cliente FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
);

CREATE TABLE mecanico (
    id_mecanico NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identificador VARCHAR2(50) UNIQUE NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    especialidad VARCHAR2(100)
);

CREATE TABLE repuesto (
    id_repuesto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(50) UNIQUE NOT NULL,
    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(255),
    precio NUMBER(10, 2) CHECK (precio >= 0),
    cantidad_disponible NUMBER(10) CHECK (cantidad_disponible >= 0)
);

CREATE TABLE servicio (
    id_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR2(50) UNIQUE NOT NULL,
    descripcion VARCHAR2(255) NOT NULL,
    costo_mano_obra NUMBER(10, 2) CHECK (costo_mano_obra >= 0)
);

CREATE TABLE orden_trabajo (
    id_orden NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_orden VARCHAR2(50) UNIQUE NOT NULL,
    id_vehiculo NUMBER NOT NULL,
    id_mecanico NUMBER NOT NULL,
    descripcion_problema VARCHAR2(500) NOT NULL,
    estado VARCHAR2(20) CHECK (estado IN ('PENDIENTE', 'EN PROCESO', 'FINALIZADA', 'CANCELADA')),
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    total_reparacion NUMBER(10, 2) DEFAULT 0,
    CONSTRAINT fk_orden_vehiculo FOREIGN KEY (id_vehiculo) REFERENCES vehiculo(id_vehiculo),
    CONSTRAINT fk_orden_mecanico FOREIGN KEY (id_mecanico) REFERENCES mecanico(id_mecanico)
);

CREATE TABLE detalle_servicio (
    id_detalle_servicio NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden NUMBER NOT NULL,
    id_servicio NUMBER NOT NULL,
    costo NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_det_serv_orden FOREIGN KEY (id_orden) REFERENCES orden_trabajo(id_orden),
    CONSTRAINT fk_det_serv_servicio FOREIGN KEY (id_servicio) REFERENCES servicio(id_servicio)
);

CREATE TABLE detalle_repuesto (
    id_detalle_repuesto NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden NUMBER NOT NULL,
    id_repuesto NUMBER NOT NULL,
    cantidad NUMBER(10) NOT NULL,
    precio_unitario NUMBER(10, 2) NOT NULL,
    subtotal NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_det_rep_orden FOREIGN KEY (id_orden) REFERENCES orden_trabajo(id_orden),
    CONSTRAINT fk_det_rep_repuesto FOREIGN KEY (id_repuesto) REFERENCES repuesto(id_repuesto)
);

